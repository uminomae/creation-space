import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');
const versionFile = path.join(repoRoot, 'src', 'version.js');

function git(args) {
  return execFileSync('git', ['-C', repoRoot, ...args], { encoding: 'utf8' }).trim();
}

function getTokyoDateParts() {
  const parts = new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Asia/Tokyo',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).formatToParts(new Date());

  const part = Object.fromEntries(parts.filter(({ type }) => type !== 'literal').map(({ type, value }) => [type, value]));
  return {
    year: part.year,
    month: part.month,
    day: part.day,
  };
}

const commitCount = Number(git(['rev-list', '--count', 'HEAD'])) + 1;
const { year, month, day } = getTokyoDateParts();
const version = `v0.${commitCount}.0`;
const date = `${year}-${month}-${day}`;

const output = `// Auto-updated by scripts/bump-dev-version.mjs via .githooks/pre-commit.\n` +
  `// Do not edit this file manually unless the hook/bootstrap is being repaired.\n` +
  `export const DEV_VERSION = '${version}';\n` +
  `export const DEV_VERSION_DATE = '${date}';\n`;

writeFileSync(versionFile, output, 'utf8');
process.stdout.write(`${version} ${date}\n`);
